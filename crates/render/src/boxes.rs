/// Buttons, labels and checkboxes are activated by clicking anywhere in
/// them: their content links to this internal URL, so the inline layout's
/// link hit-testing does the work.
pub fn activation_url(node: NodeId) -> Arc<Url> {
    use slotmap::Key as _;
    Arc::new(Url::parse(&format!("feather-activate:{}", node.data().as_ffi())).expect("valid URL"))
}

/// The element an [`activation_url`] points at.
pub fn activation_target(url: &Url) -> Option<NodeId> {
    (url.scheme() == "feather-activate").then(|| url.path().parse::<u64>().ok()).flatten().map(|v| slotmap::KeyData::from_ffi(v).into())
}

/// A table cell's flex sizing, derived from its whole column so that every
/// row lays out the same way and columns line up.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct CellLayout {
    pub basis: f32,
    pub grow: f32,
    pub min: f32,
    /// A percentage column (`width="25%"`): this share of the row, px basis ignored.
    pub percent: Option<f32>,
}

impl Block {
    /// Can this block be cut into horizontal slices (one per child row) without
    /// visibly changing it? Then its children become top-level rows, which is
    /// what keeps long pages virtualizable.
    fn is_splittable(&self) -> bool {
        self.kind == BlockKind::Normal && self.sliceable_box()
    }

    /// The box itself (ignoring its layout mode) survives being sliced.
    fn sliceable_box(&self) -> bool {
        let s = &self.style;
        // `min-height: 100vh` page wrappers: the content is taller anyway.
        let min_height_ok = match s.min_height {
            Length::Auto | Length::Percent(_) => true,
            Length::Px(_) => self.children.len() > 3 && s.painted_background().is_none(),
        };
        s.border_width.top == 0.0
            && s.border_width.bottom == 0.0
            && s.border_radius.iter().all(|r| r.px_or_zero() == 0.0)
            && s.height.is_auto()
            && min_height_ok
            && s.max_height.is_auto()
            && s.overflow == Overflow::Visible
            && s.opacity >= 1.0
            && s.position != style::Position::Absolute
            && s.position != style::Position::Fixed
    }

    /// A grid or a flex column that can be cut between its rows of items:
    /// returns it as a plain block whose children are the slices (or, for a
    /// one-column stack, the items themselves), so the flattener can split
    /// it like any other block. Long pages are mostly made of these now.
    #[allow(clippy::result_large_err)]
    fn into_stack(mut self) -> Result<Block, Block> {
        let s = self.style.clone();
        if !self.sliceable_box() || self.children.len() < 2 {
            return Err(self);
        }
        let columns = match self.kind {
            BlockKind::Grid => match s.grid_columns {
                Some(n) if n >= 1 => n as usize,
                _ => return Err(self),
            },
            BlockKind::Flex
                if s.flex_direction == FlexDirection::Column
                    && !s.flex_wrap
                    && matches!(s.justify_content, None | Some(Justify::Start)) =>
            {
                1
            }
            _ => return Err(self),
        };
        // A single row of items (including our own slices) stays whole.
        if self.children.len() <= columns {
            return Err(self);
        }
        // Spanning or explicitly placed items (which may share a cell) need the real grid.
        let spans = self.children.iter().any(|c| {
            matches!(c, LayoutBox::Block(b) if b.style.grid_column.is_some() || b.style.grid_row_start.is_some() || b.style.grid_column_start.is_some())
        });
        if spans {
            return Err(self);
        }
        let gap = s.row_gap.px_or_zero();
        let stretch = matches!(s.align_items, None | Some(Align::Stretch));
        let children = std::mem::take(&mut self.children);
        let mut out: Vec<LayoutBox> = Vec::new();
        if columns == 1 && stretch {
            // A stack of full-width items: they're just blocks in a row.
            for (i, mut child) in children.into_iter().enumerate() {
                if i > 0 && gap > 0.0 {
                    // Gaps don't collapse with margins.
                    if let LayoutBox::Block(b) = &mut child {
                        let st = Arc::make_mut(&mut b.style);
                        st.margin.top = Length::Px(st.margin.top.px_or_zero() + gap);
                    } else {
                        out.push(LayoutBox::Block(Block::spacer(&s, gap)));
                    }
                }
                out.push(child);
            }
        } else {
            // One copy of the container per row of items; the copies agree on
            // column widths because they have the same template and width.
            let mut slice_style = (*s).clone();
            slice_style.margin = Edges::all(Length::ZERO);
            slice_style.padding = Edges::all(Length::ZERO);
            slice_style.border_width = Edges::all(0.0);
            slice_style.background = None;
            slice_style.background_image = None;
            slice_style.gradients = None;
            slice_style.background_url = None;
            slice_style.width = Length::Auto;
            slice_style.min_width = Length::Auto;
            slice_style.max_width = Length::Auto;
            slice_style.min_height = Length::Auto;
            let mut items = children.into_iter().peekable();
            let mut row = 0;
            while items.peek().is_some() {
                let group: Vec<LayoutBox> = items.by_ref().take(columns).collect();
                let mut st = slice_style.clone();
                if row > 0 {
                    st.margin.top = Length::Px(gap);
                }
                out.push(LayoutBox::Block(Block {
                    // Unique and stable: GPUI element ids come from these.
                    id: (1 << 40) + (self.id << 16) + row,
                    // No hover reporting: moving between slices would look like
                    // leaving and re-entering the container.
                    node: None,
                    style: Arc::new(st),
                    kind: self.kind.clone(),
                    children: group,
                    anchors: Vec::new(),
                    min_content: self.min_content,
                    max_content: self.max_content,
                    colspan: 1,
                    cell: None,
                    heading: false,
                }));
                row += 1;
            }
        }
        self.children = out;
        self.kind = BlockKind::Normal;
        Ok(self)
    }

    fn spacer(parent: &ComputedStyle, height: f32) -> Block {
        let mut st = ComputedStyle::anonymous(parent);
        st.display = style::Display::Block;
        st.height = Length::Px(height);
        Block {
            id: usize::MAX / 2,
            node: None,
            style: Arc::new(st),
            kind: BlockKind::Normal,
            children: Vec::new(),
            anchors: Vec::new(),
            min_content: 0.0,
            max_content: 0.0,
            colspan: 1,
            cell: None,
            heading: false,
        }
    }

    /// When split, does it need a wrapper layer around each slice (vs. a plain indent)?
    fn needs_wrapper(&self) -> bool {
        let s = &self.style;
        let fancy = |l: Length| !matches!(l, Length::Px(_));
        s.painted_background().is_some()
            || s.border_width.left > 0.0
            || s.border_width.right > 0.0
            || !s.width.is_auto()
            || !s.min_width.is_auto()
            || !s.max_width.is_auto()
            || fancy(s.margin.left)
            || fancy(s.margin.right)
            || fancy(s.padding.left)
            || fancy(s.padding.right)
    }
}

/// The text-relevant subset of a style, per span.
#[derive(Debug, Clone, PartialEq)]
pub struct InlineStyle {
    pub font_size: f32,
    pub line_height: LineHeight,
    pub font_weight: u16,
    pub italic: bool,
    pub font_family: FontFamily,
    pub font_names: style::FontNames,
    pub color: Color,
    pub background: Option<Color>,
    pub underline: bool,
    pub strikethrough: bool,
    /// How far this text's baseline is raised (px, negative = lowered), from
    /// `vertical-align` on it and its inline ancestors.
    pub baseline_shift: f32,
    /// The innermost element this text belongs to (for `:hover`).
    pub node: Option<NodeId>,
    pub cursor: style::Cursor,
    /// Gradient text: glyph colors across the span (instead of `color`).
    pub gradient: Option<Arc<style::TextGradient>>,
    /// `pointer-events: none` (or hidden): the mouse goes through.
    pub inert: bool,
}

impl InlineStyle {
    pub(crate) fn of(s: &ComputedStyle, is_inline_box: bool) -> Self {
        Self {
            font_size: s.font_size,
            line_height: s.line_height,
            font_weight: s.font_weight,
            italic: s.italic,
            font_family: s.font_family,
            font_names: s.font_names.clone(),
            color: if s.visible { s.color } else { Color::TRANSPARENT },
            // Block backgrounds are painted by the block; only inline ones go on text runs.
            background: if is_inline_box && s.visible { s.painted_background() } else { None },
            underline: s.underline,
            strikethrough: s.strikethrough,
            baseline_shift: 0.0,
            node: None,
            cursor: s.cursor,
            gradient: s.text_gradient.clone().filter(|_| s.visible),
            inert: s.pointer_events_none || !s.visible,
        }
    }
}

