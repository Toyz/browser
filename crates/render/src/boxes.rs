        assert_eq!(pieces[0], ("Hello", PieceKind::Word, false));
        assert_eq!(pieces[1], (" ", PieceKind::Space, false));
        // "wor" + "ld" are one word across a span boundary: no break between.
        assert_eq!(pieces[2], ("wor", PieceKind::Word, true));
