        // Superscript is raised and smaller.
        let sup = p.spans.iter().find(|s| s.style.baseline_shift > 0.0).expect("raised span");
        assert!(sup.style.font_size < 16.0);
        // The code chip is a decorated inline box.
        assert_eq!(p.boxes.len(), 1);
