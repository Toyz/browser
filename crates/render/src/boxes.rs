        assert!(p.text[p.boxes[0].range.clone()].contains(".rs"));
        // Every span knows its element (for :hover): "wor" is inside <b>.
        let b = p.spans.iter().find(|s| s.style.font_weight == 700).unwrap();
        assert!(b.style.node.is_some());
